# LOCAL TEST KIT: one-time setup on Windows. Run from the repo folder:  powershell -ExecutionPolicy Bypass -File scripts\local-setup.ps1
# Checks Node and Docker, creates .env.local with random secrets, starts Postgres, installs, migrates and loads demo data.
$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")

function Fail($msg) { Write-Host ""; Write-Host "PROBLEM: $msg" -ForegroundColor Red; exit 1 }

# 1. Node 20+
$node = Get-Command node -ErrorAction SilentlyContinue
if (-not $node) { Fail "Node.js is not installed. Download the LTS version from https://nodejs.org (click the big green button), install it, then close and reopen PowerShell and run this again." }
$major = [int](((node -v) -replace "^v", "").Split(".")[0])
if ($major -lt 20) { Fail "Node.js $(node -v) is too old. Install the current LTS version from https://nodejs.org, reopen PowerShell, and run this again." }

# 2. Docker
$docker = Get-Command docker -ErrorAction SilentlyContinue
if (-not $docker) { Fail "Docker is not installed. Install Docker Desktop from https://www.docker.com/products/docker-desktop/ , start it, wait until it says it is running, then run this again." }
$ErrorActionPreference = "Continue"
docker info *> $null
$dockerOk = ($LASTEXITCODE -eq 0)
$ErrorActionPreference = "Stop"
if (-not $dockerOk) { Fail "Docker is installed but not running. Open Docker Desktop, wait until it says 'Engine running', then run this again. (Help: https://docs.docker.com/desktop/setup/install/windows-install/)" }

# 3. .env.local with random secrets (never overwritten, so your data keeps working)
function B64($n) { $b = New-Object byte[] $n; [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b); [Convert]::ToBase64String($b) }
function Hex($n) { $b = New-Object byte[] $n; [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b); -join ($b | ForEach-Object { $_.ToString("x2") }) }
if (Test-Path ".env.local") {
  Write-Host ".env.local already exists. Keeping it."
} else {
  $skip = "^(APP_URL|DATABASE_URL|NODE_ENV|APP_MODE|ADMIN_APP_URL|SESSION_SECRET|MESSAGING_SETTINGS_KEY|OFFER_LINK_TOKEN_KEY|ID_IMAGE_KEY|ID_RETENTION_CRON_SECRET|SMS_CODE_SECRET|ID_CHECK_WEBHOOK_SECRET|ALERT_UNSUBSCRIBE_KEY|ALERT_CRON_SECRET|ALERT_DELIVERY|PAYWAY_WEBHOOK_SECRET|DEV_LOGIN)="
  $lines = @(Get-Content ".env.example" | Where-Object { $_ -notmatch $skip -and $_ -notmatch "^# AI_[A-Z_]+=$" })
  $lines += ""
  $lines += "# --- Local test kit (generated by scripts/local-setup.ps1; local use only) ---"
  $lines += "DEV_LOGIN=1"
  $lines += "INVESTMENT_MODULE_ENABLED=true"
  $lines += "APP_URL=http://localhost:3005"
  $lines += "ADMIN_APP_URL=http://localhost:3006"
  $lines += "DATABASE_URL=postgres://ownerlisting:localtest@localhost:5544/ownerlisting"
  $lines += "SESSION_SECRET=$(B64 48)"
  $lines += "MESSAGING_SETTINGS_KEY=$(B64 32)"
  $lines += "OFFER_LINK_TOKEN_KEY=$(B64 32)"
  $lines += "ID_IMAGE_KEY=$(B64 32)"
  $lines += "ID_RETENTION_CRON_SECRET=$(Hex 32)"
  $lines += "SMS_CODE_SECRET=$(B64 48)"
  $lines += "ID_CHECK_WEBHOOK_SECRET=$(Hex 32)"
  $lines += "ALERT_UNSUBSCRIBE_KEY=$(B64 48)"
  $lines += "ALERT_CRON_SECRET=$(Hex 32)"
  $lines += "ALERT_DELIVERY=console"
  $lines += "PAYWAY_WEBHOOK_SECRET=$(Hex 32)"
  $lines += "# Optional AI test with Ollama on this PC (docs/LOCAL_TEST.md). Remove the # from the three lines, restart the sites,"
  $lines += "# then a super admin turns AI on at /staff/ai. Use the model name exactly as 'ollama list' shows it."
  $lines += "# AI_ENGINE=ollama"
  $lines += "# AI_ENDPOINT=http://127.0.0.1:11434"
  $lines += "# AI_MODEL=llama3.1:8b"
  [System.IO.File]::WriteAllText((Join-Path (Get-Location).Path ".env.local"), (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))
  Write-Host "Created .env.local with fresh random secrets."
}

# 3b. Local-kit values, also added to an older .env.local (only when the line is missing or empty; your own values are kept).
# Dummy Google keys: without them the site treats sign-in as switched off, so /dev-login works but API calls look signed out.
function Ensure-Env($key, $value) {
  $path = Join-Path (Get-Location).Path ".env.local"
  $lines = @([System.IO.File]::ReadAllLines($path))
  if ($lines | Where-Object { $_ -match "^$key=.+" }) { return }
  if ($lines | Where-Object { $_ -eq "$key=" }) {
    $lines = @($lines | ForEach-Object { if ($_ -eq "$key=") { "$key=$value" } else { $_ } })
  } else {
    $lines += "$key=$value"
  }
  [System.IO.File]::WriteAllText($path, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))
}
Ensure-Env "GOOGLE_CLIENT_ID" "local-dummy"
Ensure-Env "GOOGLE_CLIENT_SECRET" "local-dummy"
Ensure-Env "LOCAL_STORAGE_DIR" (Join-Path (Get-Location).Path ".local-storage")
Ensure-Env "MALWARE_SCAN_DRIVER" "local-noop"
Ensure-Env "MANDATE_FLOOR_KEY" (B64 32)

# 4. Postgres
Write-Host "Starting the database (first time downloads about 150 MB)..."
docker compose -f docker-compose.local.yml up -d --wait
if ($LASTEXITCODE -ne 0) { Fail "The database did not start. Is port 5544 already in use? Run: docker compose -f docker-compose.local.yml logs" }

# 5. Install, migrate, seed
Write-Host "Installing packages (a few minutes the first time)..."
npm install --no-package-lock
if ($LASTEXITCODE -ne 0) { Fail "npm install failed. Check your internet connection and run this again." }
node --env-file=.env.local scripts/migrate.mjs
if ($LASTEXITCODE -ne 0) { Fail "Database setup (migrate) failed. See the message above." }
node --env-file=.env.local scripts/seed-demo.mjs
if ($LASTEXITCODE -ne 0) { Fail "Loading demo data failed. See the message above." }

Write-Host ""
Write-Host "All set. Now run:  powershell -ExecutionPolicy Bypass -File scripts\local-start.ps1" -ForegroundColor Green
Write-Host "Then open http://localhost:3005/dev-login (public site) and http://localhost:3006/dev-login (admin site)."
