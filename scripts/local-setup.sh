#!/usr/bin/env bash
# LOCAL TEST KIT: one-time setup on Mac/Linux. Run from anywhere:  bash scripts/local-setup.sh
set -euo pipefail
cd "$(dirname "$0")/.."
fail() { echo; echo "PROBLEM: $1" >&2; exit 1; }

command -v node >/dev/null || fail "Node.js is not installed. Get the LTS version from https://nodejs.org, then run this again."
[ "$(node -p 'process.versions.node.split(".")[0]')" -ge 20 ] || fail "Node.js $(node -v) is too old. Install the current LTS from https://nodejs.org."
command -v docker >/dev/null || fail "Docker is not installed. Install Docker Desktop from https://www.docker.com/products/docker-desktop/ and start it."
docker info >/dev/null 2>&1 || fail "Docker is installed but not running. Start Docker Desktop and wait until it is ready."
command -v openssl >/dev/null || fail "openssl is needed to generate secrets."

if [ -f .env.local ]; then
  echo ".env.local already exists. Keeping it."
else
  {
    grep -vE '^(APP_URL|DATABASE_URL|NODE_ENV|APP_MODE|ADMIN_APP_URL|SESSION_SECRET|MESSAGING_SETTINGS_KEY|OFFER_LINK_TOKEN_KEY|ID_IMAGE_KEY|ID_RETENTION_CRON_SECRET|SMS_CODE_SECRET|ID_CHECK_WEBHOOK_SECRET|ALERT_UNSUBSCRIBE_KEY|ALERT_CRON_SECRET|ALERT_DELIVERY|PAYWAY_WEBHOOK_SECRET|DEV_LOGIN)=' .env.example | grep -vE '^# AI_[A-Z_]+=$' || true
    echo
    echo "# --- Local test kit (generated by scripts/local-setup.sh; local use only) ---"
    echo "DEV_LOGIN=1"
    echo "APP_URL=http://localhost:3005"
    echo "ADMIN_APP_URL=http://localhost:3006"
    echo "DATABASE_URL=postgres://ownerlisting:localtest@localhost:5544/ownerlisting"
    echo "SESSION_SECRET=$(openssl rand -base64 48 | tr -d '\n')"
    echo "MESSAGING_SETTINGS_KEY=$(openssl rand -base64 32)"
    echo "OFFER_LINK_TOKEN_KEY=$(openssl rand -base64 32)"
    echo "ID_IMAGE_KEY=$(openssl rand -base64 32)"
    echo "ID_RETENTION_CRON_SECRET=$(openssl rand -hex 32)"
    echo "SMS_CODE_SECRET=$(openssl rand -base64 48 | tr -d '\n')"
    echo "ID_CHECK_WEBHOOK_SECRET=$(openssl rand -hex 32)"
    echo "ALERT_UNSUBSCRIBE_KEY=$(openssl rand -base64 48 | tr -d '\n')"
    echo "ALERT_CRON_SECRET=$(openssl rand -hex 32)"
    echo "ALERT_DELIVERY=console"
    echo "PAYWAY_WEBHOOK_SECRET=$(openssl rand -hex 32)"
    echo "# Optional AI test with Ollama on this computer (docs/LOCAL_TEST.md). Remove the # from the three lines, restart the sites,"
    echo "# then a super admin turns AI on at /staff/ai. Use the model name exactly as 'ollama list' shows it."
    echo "# AI_ENGINE=ollama"
    echo "# AI_ENDPOINT=http://127.0.0.1:11434"
    echo "# AI_MODEL=llama3.1:8b"
  } > .env.local
  echo "Created .env.local with fresh random secrets."
fi

# Local-kit values, also added to an older .env.local (only when the line is missing or empty; your own values are kept).
# Dummy Google keys: without them the site treats sign-in as switched off, so /dev-login works but API calls look signed out.
ensure_env() {
  if grep -qE "^$1=.+" .env.local; then return; fi
  [ -n "$(tail -c1 .env.local)" ] && echo >> .env.local
  if grep -qE "^$1=" .env.local; then
    tmp="$(mktemp)"; awk -v k="$1" -v v="$2" 'index($0, k "=") == 1 { print k "=" v; next } { print }' .env.local > "$tmp" && cat "$tmp" > .env.local && rm -f "$tmp"
  else
    echo "$1=$2" >> .env.local
  fi
}
ensure_env GOOGLE_CLIENT_ID local-dummy
ensure_env GOOGLE_CLIENT_SECRET local-dummy
ensure_env LOCAL_STORAGE_DIR "$(pwd)/.local-storage"
ensure_env MALWARE_SCAN_DRIVER local-noop

echo "Starting the database..."
docker compose -f docker-compose.local.yml up -d --wait || fail "The database did not start. Is port 5544 in use?"
echo "Installing packages..."
npm install --no-package-lock || fail "npm install failed."
node --env-file=.env.local scripts/migrate.mjs || fail "Database setup (migrate) failed."
node --env-file=.env.local scripts/seed-demo.mjs || fail "Loading demo data failed."
echo
echo "All set. Now run: bash scripts/local-start.sh"
echo "Then open http://localhost:3005/dev-login (public) and http://localhost:3006/dev-login (admin)."
